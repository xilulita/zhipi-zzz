  function buildEssay(grade, genre, note) {
    const poolKey = keyOf(note);
    const P = POOLS[poolKey] || POOLS.growth;
    const [lo, hi] = grade.range;
    // 目标字数：落在区间内偏上位置（约 60%~85%），确保不越界
    const span = hi - lo;
    const target = Math.round(lo + span * (0.58 + Math.random() * 0.24));
    const title = P.title;
    const paras = [];

    const detail = [];
    const acts = P.acts.slice();
    while (detail.length < 3 && acts.length) {
      const a = acts.splice(Math.floor(Math.random() * acts.length), 1)[0];
      detail.push(a);
    }
    const feel = pick(P.feel);

    // 段落骨架（基础长度约 150~220 字）
    paras.push(pick(P.open));
    paras.push(`那是一个再普通不过的下午。${detail[0]}，${detail[1] || ''}。我站在不远处，什么也没做，只是看着。${feel}。`);
    paras.push(`我试着做点什么。${pick(SENT.do)}。${pick(SENT.say)}话一出口，我才发现原来没有想象中那么难。${detail[2] ? detail[2] + '。' : ''}`);
    paras.push(P.mid);
    paras.push(P.end[0] + pick(SENT.jump));

    const filler = [
      '我记得那天的光很柔和，把一切都照得像旧电影。',
      '有风从窗口进来，吹动书页，也吹动我的心思。',
      '我想了很久，最后还是什么也没说。',
      '那一点点小事，被我记得很久很久。',
      '回家的路上，我一直在想刚才发生的每一句话。',
      '路边的人来来往往，没有人注意到我停了半步。',
      '我忽然明白，有些改变是从一个很小的瞬间开始的。',
      '后来每到这个季节，我都会想起那天的空气。',
      '桌上的日历已经翻过去好几页，那件事却像昨天。',
      '我把这件事写进作文本，老师看了很久。'
    ];

    const lenOf = arr => arr.join('').length;
    // 扩充：优先加在中间叙述段（2、3 段），再轮到其他段
    const order = [2, 1, 3, 4, 0];
    let guard = 0;
    while (lenOf(paras) < target && guard < 200) {
      guard++;
      const idx = order[guard % order.length];
      const add = pick(filler) + pick(P.feel) + '。';
      // 若加入后超出上限，换更短的句子
      if (lenOf(paras) + add.length > target + 8) {
        const shorter = pick(filler);
        if (lenOf(paras) + shorter.length > target + 8) break;
        paras[idx] += shorter;
      } else {
        paras[idx] += add;
      }
    }

    // 超长则裁剪（删末尾冗余句，从最长段开始）
    while (lenOf(paras) > hi - 6 && guard < 400) {
      guard++;
      let longest = 0;
      paras.forEach((p, i) => { if (i > 0 && p.length > paras[longest].length) longest = i; });
      const p = paras[longest];
      const cut = p.lastIndexOf('。');
      if (cut <= 30) break;
      paras[longest] = p.slice(0, cut + 1);
    }

    // 备注中的提醒，写入首段后（保持可读）
    if (note) {
      const m = note.match(/提醒\s*[:：]\s*([^)）\n]+)/);
      if (m && lenOf(paras) < hi - 20) {
        paras[1] = paras[1] + `（按老师提醒：${m[1].trim()}）`;
      }
    }

    return { title, paras, words: lenOf(paras), pool: poolKey, genre: genre };
  }

