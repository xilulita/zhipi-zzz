  function analyze(text, dotJson) {
    const words = text.replace(/\s/g, '').length;
    const sents = text.split(/[。！？]/).filter(s => s.trim().length > 3);
    const paras = (dotJson && dotJson.blocks) ? dotJson.blocks.length : sents.length / 3;
    const avgLen = words / Math.max(1, sents.length);
    const r = { words, sents: sents.length, paras: Math.round(paras), avgLen: Math.round(avgLen) };
    r.detailRatio = Math.min(1, r.paras / 5);
    r.fluency = avgLen > 42 ? 0.72 : avgLen < 12 ? 0.78 : 0.9;
    r.rich = /比喻|像|仿佛|如同|似的/.test(text) ? 0.86 : 0.68;
    return r;
  }

  function scoreOf(grade, weights, text, targets) {
    const s = analyze(text, targets);
    const seed = Math.min(0.98, Math.max(0.55,
      (s.fluency * 0.5 + s.rich * 0.35 + s.detailRatio * 0.15) + rand(-0.04, 0.05)));
    const quant = {}; // 每个维度的质量分 0~1
    quant.content = seed * 0.96 + rand(-0.03, 0.04);
    quant.structure = seed * 0.94 + rand(-0.03, 0.045);
    quant.language = seed * 0.98 + rand(-0.04, 0.04);
    quant.norm = 0.86 + rand(-0.04, 0.09);
    Object.keys(quant).forEach(k => quant[k] = Math.min(0.99, Math.max(0.52, quant[k])));

    const points = {};
    let total = 0;
    DIMS.forEach((d, i) => {
      const full = Math.round(grade.total * weights[i] / 100 * 10) / 10;
      let p = Math.round(full * quant[d.key]);
      points[d.key] = { got: p, full, quant: quant[d.key] };
      total += p;
    });
    return { points, total, stats: s };
  }

  function levelOf(grade, total) {
    const ratio = total / grade.total;
    if (ratio >= grade.tier.one) return { name: grade.levels.one, key: 'one', desc: '优秀', color: '#22a06b' };
    if (ratio >= grade.tier.two) return { name: grade.levels.two, key: 'two', desc: '良好', color: '#5b5ce2' };
    return { name: grade.levels.three, key: 'three', desc: '合格', color: '#e08a35' };
  }

